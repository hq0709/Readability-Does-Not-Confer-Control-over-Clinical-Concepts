"""Macros for the analyses added in the journal version (journal/journal_numbers.tex).
Inputs: data/journal/two_way.json, data/journal/common_support.json, produced by
scripts/two_way.py and scripts/common_support.py from the released campaign runs/."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
T = json.load(open(ROOT / "data/journal/two_way.json"))
C = json.load(open(ROOT / "data/journal/common_support.json"))
M = {}
pct = lambda a, b: f"{round(100 * a / b):d}"
for key, dom in (("Chest", "chest"), ("Coco", "coco"), ("Nih", "nih"), ("Chex", "chexpert")):
    d = T[dom]
    M[f"jnRef{key}"] = d["ref"]
    M[f"jnRefLost{key}"] = d["ref_lost_competitor"]
    M[f"jnOwned{key}"] = d["owned"]
    M[f"jnColSpec{key}"] = d["col_specific"]
    M[f"jnTwoWay{key}"] = d["two_way"]
    M[f"jnTwoWay{key}Pct"] = pct(d["two_way"], d["n"])
    M[f"jnOwnedNotCol{key}"] = d["owned_not_colspec"]
    M[f"jnRefNotTwoWay{key}"] = d["ref"] - d["two_way"]
    M[f"jnRefNotTwoWay{key}Pct"] = pct(d["ref"] - d["two_way"], d["ref"])
    M[f"jnKappaMed{key}"] = f"{d['median_kappa']:.2f}"
    M[f"jnKappaOwnedMed{key}"] = f"{d['median_kappa_owned']:.2f}"
    M[f"jnOffTarget{key}"] = f"{d['median_offtarget_ratio_ref']:.1f}" if key != "Coco" else f"{d['median_offtarget_ratio_ref']:.2f}"
    for k in (1, 2, 3, 4):
        M[f"jnSub{['', 'One', 'Two', 'Three', 'Four'][k]}{key}"] = f"{d[f'own_sub{k}_mean']:.1f}"
for tag, k in (("Eighty", "auroc_ge_0.80"), ("EightyFive", "auroc_ge_0.85")):
    d = C[k]
    M[f"jnCs{tag}ChestN"] = d["chest_cells"]
    M[f"jnCs{tag}ChestOwned"] = d["chest_owned"]
    M[f"jnCs{tag}ChestPct"] = pct(d["chest_owned"], d["chest_cells"])
    M[f"jnCs{tag}NihN"] = d["chest_nih"]
    M[f"jnCs{tag}NihOwned"] = d["chest_nih_owned"]
    M[f"jnCs{tag}NatN"] = d["natural_cells"]
    M[f"jnCs{tag}NatOwned"] = d["natural_owned"]
    M[f"jnCs{tag}NatPct"] = pct(d["natural_owned"], d["natural_cells"])
    M[f"jnCs{tag}Adj"] = f"{d['adjusted_difference']:.2f}"
    M[f"jnCs{tag}AdjSd"] = f"{d['bootstrap_sd']:.2f}"
    M[f"jnCs{tag}AurocChest"] = f"{d['median_auroc_chest']:.2f}"
    M[f"jnCs{tag}AurocNat"] = f"{d['median_auroc_natural']:.2f}"
t = C["top_bin_ge_0.90"]
M["jnTopDiff"] = f"{t['difference']:.3f}"
M["jnTopDiffSd"] = f"{t['bootstrap_sd']:.3f}"
assert t["chest_owned"] == 12 and t["chest_cells"] == 37, "top bin no longer matches cfStratChestTop*"
# protocol constants stated in the ACL text (sections/3_framework.tex, 4_setup.tex, 5_results.tex) and the
# common-support cutoffs of scripts/common_support.py
M["jnCsAurocLower"], M["jnCsAurocHigher"] = "0.80", "0.85"
M["jnOwnedRankMin"], M["jnOwnedRankMax"] = 1, 6
M["jnRandomDirections"] = 119
M["jnScoredAnswersMillions"] = 30
out = ROOT / "journal/journal_numbers.tex"
out.write_text("% Generated by scripts/build_journal_numbers.py; do not edit by hand.\n" + "".join(
    f"\\providecommand{{\\{k}}}{{}}\\renewcommand{{\\{k}}}{{{v}}}\n" for k, v in M.items()))
print(out.read_text())
