"""Write ACL-width copies of the four figure scripts whose layout is absolute inches.

Those scripts place every panel with f.add_axes(rect(FW, FH, x, y, w, h)) in inches, so changing
fs.WIDTH alone widens the canvas and leaves the panels where they were. Scaling every inch constant
by the same factor moves the whole composition to the new width unchanged -- the panels grow, the
margins grow with them, and the type stays at the point size it was written at, which is the point:
at 5.5 in those 8.5 pt titles printed at 9.8 pt because the page enlarged the figure.

The originals under rebuild/scripts are not modified. Each copy records the factor it was built with.
"""
from __future__ import annotations

from pathlib import Path

import aclsize

K = aclsize.K
SRC = Path(__file__).resolve().parents[1] / "scripts"
HERE = Path(__file__).resolve().parent

HEAD = f'''# Generated by make_resized.py: every absolute inch constant of the original multiplied by
# K = {K:.4f} = 455.24 pt (ACL text width) / 5.5 in (the width the original was authored at).
# Do not edit here; edit the original and regenerate.
'''
# `from __future__` must stay first in the file, so the factor is bound just after it
FUTURE = "from __future__ import annotations"
BIND = f"{FUTURE}\n\nK_ACL = {K!r}" 

# (module, [(exact source text, replacement)])
EDITS = {
    "figure03": [
        ("FW, FH = fs.WIDTH, 3.30",
         f"FW, FH = fs.WIDTH, 3.30 * {K!r}"),
        ("flow_panels(f, FW, FH, y0=0.44, PH=2.20, PW=1.72, xl=0.10, letters=\"abc\")",
         f"flow_panels(f, FW, FH, y0=0.44 * {K!r}, PH=2.20 * {K!r}, PW=1.72 * {K!r}, xl=0.10 * {K!r}, letters=\"abc\")"),
        ("f.text(0.5, 0.17 / FH,",
         f"f.text(0.5, 0.17 * {K!r} / FH,"),
    ],
    "figure04": [
        ("FW, FH = fs.WIDTH, 3.66",
         f"FW, FH = fs.WIDTH, 3.66 * {K!r}"),
        ("img_w, img_x = 1.02, 0.12; bar_x, bar_w = 1.96, 3.22; ax_h = 1.15",
         f"img_w, img_x = 1.02 * {K!r}, 0.12 * {K!r}; bar_x, bar_w = 1.96 * {K!r}, 3.22 * {K!r}; ax_h = 1.15 * {K!r}"),
        ("row_y = [2.28, 0.76]; title_y = [3.49, 1.96]",
         f"row_y = [2.28 * {K!r}, 0.76 * {K!r}]; title_y = [3.49 * {K!r}, 1.96 * {K!r}]"),
    ],
    "figure06": [
        ("FW = fs.WIDTH; P = 1.36; gap = 0.20; x0 = 0.98; Ph = P * YE[-1] / 6",
         f"FW = fs.WIDTH; P = 1.36 * {K!r}; gap = 0.20 * {K!r}; x0 = 0.98 * {K!r}; Ph = P * YE[-1] / 6"),
        ("FH = 0.22 + Ph + 0.36 + 0.16 + 0.62",
         f"FH = (0.22 + 0.36 + 0.16 + 0.62) * {K!r} + Ph"),
        ("ax = f.add_axes(f5.rect(FW, FH, x0 + k * (P + gap), FH - 0.22 - Ph, P, Ph), label=f\"h{k}\")",
         f"ax = f.add_axes(f5.rect(FW, FH, x0 + k * (P + gap), FH - 0.22 * {K!r} - Ph, P, Ph), label=f\"h{{k}}\")"),
        ("cax = f.add_axes(f5.rect(FW, FH, 0.95, 0.40, 2.3, 0.08), label=\"cbar\")",
         f"cax = f.add_axes(f5.rect(FW, FH, 0.95 * {K!r}, 0.40 * {K!r}, 2.3 * {K!r}, 0.08 * {K!r}), label=\"cbar\")"),
        ("bbox_to_anchor=(3.55 / FW, 0.44 / FH)",
         f"bbox_to_anchor=(3.55 * {K!r} / FW, 0.44 * {K!r} / FH)"),
    ],
    "figure07": [
        ("f = plt.figure(figsize=(fs.WIDTH, 2.95), layout=\"constrained\")",
         "f = plt.figure(figsize=(fs.WIDTH, 2.95 * K_ACL), layout=\"constrained\")"),
        # the legend reads "largest $O_q$ at the largest size"; a mathtext subscript sets at 0.7 of its
        # base, so a 7 pt legend puts that q at 4.9 pt, under the 5 pt floor. 7.5 pt puts it at 5.25.
        ("f.legend(handles=handles, loc=\"outside lower center\", ncol=4, fontsize=7, frameon=False",
         "f.legend(handles=handles, loc=\"outside lower center\", ncol=4, fontsize=7.5, frameon=False"),
    ],
    "figure08": [
        ("P, gap, x0 = 1.25, 0.45, 0.60",
         f"P, gap, x0 = 1.25 * {K!r}, 0.45 * {K!r}, 0.60 * {K!r}"),
        ("title_h, xt_h, xl_h, bar_h = 0.40, 0.36, 0.16, 0.62",
         f"title_h, xt_h, xl_h, bar_h = 0.40 * {K!r}, 0.36 * {K!r}, 0.16 * {K!r}, 0.62 * {K!r}"),
        ("cax = f.add_axes(f5.rect(FW, FH, 1.55, 0.40, 2.4, 0.08), label=\"cbar\")",
         f"cax = f.add_axes(f5.rect(FW, FH, 1.55 * {K!r}, 0.40 * {K!r}, 2.4 * {K!r}, 0.08 * {K!r}), label=\"cbar\")"),
    ],
}


def build():
    for mod, edits in EDITS.items():
        s = (SRC / f"{mod}.py").read_text()
        for old, new in edits:
            if s.count(old) != 1:
                raise SystemExit(f"{mod}: pattern occurs {s.count(old)} times -- {old[:60]}")
            s = s.replace(old, new)
        if "K_ACL" in s:
            if s.count(FUTURE) != 1:
                raise SystemExit(f"{mod}: no single __future__ import to bind K_ACL after")
            s = s.replace(FUTURE, BIND, 1)
        (HERE / f"{mod}_acl.py").write_text(HEAD + s)
        print(f"  wrote {mod}_acl.py  ({len(edits)} constants scaled)")


if __name__ == "__main__":
    build()
